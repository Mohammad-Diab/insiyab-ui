const icon = (name, cls = 'ico') => `<svg class="${cls}" aria-hidden="true"><use href="#i-${name}"/></svg>`;

function sidebar(current) {
  return NAV.map((g) => {
    const links = g.pages.map((p) => {
      const on = p.slug === current.slug;
      return `      <a class="ins-shell-link${on ? ' is-active' : ''}" href="${p.slug}.html"${on ? ' aria-current="page"' : ''} data-keywords="${attr(p.lead ? `${p.en} ${p.lead}` : p.en)}">${icon(p.icon)}${p.title}</a>`;
    }).join('\n');
    return `      <div class="ins-shell-group">${g.group}</div>\n${links}`;
  }).join('\n\n');
}

function pageHead(p) {
  if (p.hero) return '';
  return `<header class="ins-page-head">
          <nav class="ins-breadcrumb" aria-label="مسار التنقّل">
            <ol>
              <li><a href="index.html">انسياب</a></li>
              <li><span>${p.group}</span></li>
              <li><span aria-current="page">${p.title}</span></li>
            </ol>
          </nav>
          <div class="ins-page-head-text">
            <span class="ins-eyebrow">${p.en}</span>
            <h1 class="ins-page-title">${p.title}</h1>
            <p class="ins-page-sub site-lead">${p.lead}</p>
          </div>
        </header>`;
}

/* "On this page": the page's own h2s, as chips. Only worth it from three up. */
function toc(html) {
  const heads = [...html.matchAll(/<h2 id="([^"]+)"[^>]*>([\s\S]*?)<\/h2>/g)];
  if (heads.length < 3) return '';
  const chips = heads.map(([, id, text]) => `<a href="#${id}">${text.replace(/<[^>]+>/g, '').trim()}</a>`).join('');
  return `<nav class="site-toc" aria-label="في هذه الصفحة"><span class="site-toc-label">في هذه الصفحة</span>${chips}</nav>`;
}

function pager(i) {
  const prev = PAGES[i - 1], next = PAGES[i + 1];
  const card = (p, dir) => p
    ? `<a class="site-pager-link site-pager-link--${dir}" href="${p.slug}.html"><span class="site-pager-dir">${dir === 'prev' ? 'السابق' : 'التالي'}</span><span class="site-pager-title">${p.title}</span></a>`
    : '<span></span>';
  return `<nav class="site-pager" aria-label="التنقّل بين الصفحات">${card(prev, 'prev')}${card(next, 'next')}</nav>`;
}


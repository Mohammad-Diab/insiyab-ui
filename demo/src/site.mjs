/* ==========================================================================
   Insiyab · the demo site
   ==========================================================================

   The demo is a documentation site: one page per topic, static HTML, the same
   shell on every page. It is generated rather than hand-written because the
   shell — sidebar, top bar, search, pager — is identical on ~40 pages, and
   forty hand-kept copies of one sidebar are forty chances to forget a link.

   Sources live in demo/src:

     site.mjs          this file: the page list (the one place a page is added)
     layout.html       the shell every page is poured into
     pages/<slug>.html one fragment per page — just its content

   Output is demo/<slug>.html, plain files that need no script to read. They are
   committed, so the demo works from a static host or a checkout with no build.

   Two custom tags are expanded at build time, so a page never repeats itself:

     <demo-example class="row">…live markup…</demo-example>
         renders the markup, and prints the same markup, highlighted, under it.
         `code="none"` renders without the listing.

     <demo-code lang="html|js|css|sh">…source…</demo-code>
         a listing on its own. Write the source as-is; it is escaped here.

   Run through `node build.mjs`, which calls buildSite() after the library.
   ========================================================================== */


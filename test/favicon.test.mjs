// Every docs page names the logo as its tab icon and shows it as its brand mark, and the icon files are served.
import { readdir, readFile } from 'node:fs/promises';
import { BASE } from './lib/cdp.mjs';
import { suite } from './lib/check.mjs';
const { ok, end } = suite();

const pages = [];
for (const f of (await readdir('demo')).filter((name) => name.endsWith('.html'))) {
  const html = await readFile(`demo/${f}`, 'utf8');
  if (html.includes('<!-- generated by build.mjs from demo/src/pages/')) pages.push([f, html]);
}
ok('the build wrote the docs pages', pages.length > 40, pages.length);

for (const link of ['<link rel="icon" href="../brand/favicon.ico" sizes="32x32">', '<link rel="icon" href="../brand/mark-32px.svg" type="image/svg+xml">']) {
  const missing = pages.filter(([, html]) => !html.includes(link)).map(([f]) => f);
  ok(`every page has ${link}`, missing.length === 0, missing.join(', '));
}

const unmarked = pages.filter(([, html]) => (html.match(/<span class="ins-shell-mark site-mark"><svg class="site-logo"/g) || []).length !== 2).map(([f]) => f);
ok('every page has the logo in the sidebar and in the top bar', unmarked.length === 0, unmarked.join(', '));
const home = pages.find(([f]) => f === 'index.html');
ok('the home page hero has the logo', !!home && home[1].includes('<span class="ins-shell-mark site-hero-mark site-mark"><svg class="site-logo"'));

for (const [path, type] of [['/brand/favicon.ico', 'image/x-icon'], ['/brand/mark-32px.svg', 'image/svg+xml']]) {
  const res = await fetch(`${BASE}${path}`);
  ok(`${path} is served as ${type}`, res.ok && res.headers.get('content-type') === type, `${res.status} ${res.headers.get('content-type')}`);
}

const ico = Buffer.from(await (await fetch(`${BASE}/brand/favicon.ico`)).arrayBuffer());
const sizes = Array.from({ length: ico.readUInt16LE(4) }, (_, i) => ico[6 + 16 * i]);
ok('favicon.ico is an icon of 16, 32 and 48 pixels', ico.readUInt16LE(2) === 1 && sizes.join() === '16,32,48', sizes.join());
end();

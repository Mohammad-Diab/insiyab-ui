// Turns the docs' icon sprite (demo/src/layout.html) into the gallery's Icons.axaml, so a gallery page can use the same icon as its web page: <ins:Icon Data="{StaticResource IconHome}" />.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..', '..');
const OUT = join(HERE, '..', 'gallery', 'Insiyab.Avalonia.Gallery', 'Icons.axaml');
const html = readFileSync(join(ROOT, 'demo', 'src', 'layout.html'), 'utf8');

const attr = (tag, name) => { const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`)); return m ? m[1] : null; };
const num = (tag, name) => Number(attr(tag, name) ?? 0);
const pascal = (id) => id.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

const NUM = String.raw`[-+]?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?`;

// A path's leading m is absolute in SVG but would turn relative once joined after another path; the pairs after it stay relative, hence the l.
function absoluteStart(d) {
  const m = d.match(new RegExp(`^m\\s*(${NUM})[\\s,]*(${NUM})[\\s,]*`));
  if (!m) return d;
  const rest = d.slice(m[0].length);
  return `M${m[1]} ${m[2]}${/^[-+.\d]/.test(rest) ? ' l' : ' '}${rest}`;
}

function shape(tag) {
  const kind = tag.match(/^<(\w+)/)[1];
  if (kind === 'path') return absoluteStart(attr(tag, 'd').trim());
  if (kind === 'circle') {
    const cx = num(tag, 'cx'), cy = num(tag, 'cy'), r = num(tag, 'r');
    return `M${cx - r},${cy} A${r},${r} 0 1 0 ${cx + r},${cy} A${r},${r} 0 1 0 ${cx - r},${cy} Z`;
  }
  if (kind === 'rect') {
    const x = num(tag, 'x'), y = num(tag, 'y'), w = num(tag, 'width'), h = num(tag, 'height');
    const r = Math.min(num(tag, 'rx') || num(tag, 'ry'), w / 2, h / 2);
    if (!r) return `M${x},${y} H${x + w} V${y + h} H${x} Z`;
    return `M${x + r},${y} H${x + w - r} A${r},${r} 0 0 1 ${x + w},${y + r} V${y + h - r} A${r},${r} 0 0 1 ${x + w - r},${y + h} H${x + r} A${r},${r} 0 0 1 ${x},${y + h - r} V${y + r} A${r},${r} 0 0 1 ${x + r},${y} Z`;
  }
  throw new Error(`gen-gallery-icons: <${kind}> is not handled`);
}

const lines = [];
const seen = new Set();
for (const m of html.matchAll(/<symbol id="i-([a-z0-9-]+)"[^>]*>(.*?)<\/symbol>/g)) {
  if (seen.has(m[1])) continue;
  seen.add(m[1]);
  const parts = [...m[2].matchAll(/<(?:path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*>/g)].map((t) => shape(t[0]));
  lines.push(`  <StreamGeometry x:Key="Icon${pascal(m[1])}">${parts.join(' ')}</StreamGeometry>`);
}
if (!lines.length) throw new Error('gen-gallery-icons: no symbols found');
writeFileSync(OUT, [
  '<!-- Generated by packages/avalonia/tools/gen-gallery-icons.mjs from demo/src/layout.html; do not edit. -->',
  '<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
  ...lines,
  '</ResourceDictionary>',
  '',
].join('\n'));
console.log(`gen-gallery-icons: ${lines.length} icons`);
